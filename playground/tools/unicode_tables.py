"""Write unicode-tables.js: Python's character classes as JavaScript regular expressions."""
import sys, unicodedata

def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = pred(chr(cp))
        if ok and start is None: start = cp
        if not ok and start is not None: out.append((start, cp - 1)); start = None
    if start is not None: out.append((start, 0x10FFFF))
    return out

def cls(r):
    esc = lambda c: f"\\u{{{c:x}}}"
    return "[" + "".join(esc(a) if a == b else f"{esc(a)}-{esc(b)}" for a, b in r) + "]"

tables = {"ALPHA": ranges(str.isalpha), "ALNUM": ranges(str.isalnum), "DIGIT": ranges(str.isdigit),
          "SPACE": ranges(str.isspace), "COMBINING": ranges(lambda c: unicodedata.combining(c) != 0),
          "FORMAT": ranges(lambda c: unicodedata.category(c) == "Cf")}
lines = [f"// Generated by tools/unicode_tables.py from Python {sys.version.split()[0]} (Unicode {unicodedata.unidata_version}).",
         "// Python's str.isalpha / isalnum / isdigit / isspace, unicodedata.combining and category Cf,",
         "// so the JavaScript front end treats every character exactly as the Python one."]
lines += [f"export const {k} = /{cls(r)}/u;" for k, r in tables.items()]
open("unicode-tables.js", "w").write("\n".join(lines) + "\n")
